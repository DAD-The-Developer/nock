--[[
  Nock 3.9.0: quest item drop chances.

  While a quest still needs an item that drops from mobs, Nock shows the
  chance that a kill drops it:
    * on the mob's tooltip:  Quest: Tough Wolf Meat 4/8 - drop 80%
    * under the objective in the Dashboard quest list (the best mob, in
      your zone first, and the range when several mobs drop it).
  Only items still needed; a finished objective shows nothing.

  Numbers come from Data_QuestDrops.lua (generated by
  tools/questdrops/gen_questdrops.py): which NPCs drop each quest item from
  QuestieDB Forever, the loot chance from CMaNGOS classic-db. Where no source
  gives a chance the line says "drops" without a %. These are Classic numbers;
  Forever may differ, and a small grey line says so.

  Forever API: C_QuestLog.GetNumQuestLogEntries / GetInfo /
  GetQuestObjectives (GetQuestLogLeaderBoard as a fallback), UnitGUID (the
  NPC id is the 6th part of a Creature GUID), else UnitName + zone.
  Option: NockCharDB.questDrops (on by default), Options > On screen.
]]

