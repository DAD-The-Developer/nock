local QD = {}
Nock.QuestDrops = QD
QD.NOTE = "Classic data; Forever may differ"

local function Data()
  return Nock.QuestDropsData
end

function QD.Enabled()
  local db = _G.NockCharDB
  return not (type(db) == "table" and db.questDrops == false)
end

function QD.SetEnabled(on)
  _G.NockCharDB = _G.NockCharDB or {}
  _G.NockCharDB.questDrops = on and true or false
  QD.dirty = true
  if Nock.Dash and Nock.Dash.Update then
    pcall(Nock.Dash.Update)
  end
end

local function Str(v)
  if type(v) ~= "string" or Core.IsSecret(v) then
    return nil
  end
  return v
end

-- Name indexes, built once on first use.
local itemByName, npcByName
local function Index()
  if itemByName then
    return
  end
  itemByName, npcByName = {}, {}
  local d = Data()
  if not d then
    return
  end
  for id, row in pairs(d.items) do
    itemByName[string.lower(row[1])] = id
  end
  for id, row in pairs(d.npcs) do
    local k = string.lower(row[1])
    npcByName[k] = npcByName[k] or {}
    table.insert(npcByName[k], id)
  end
end

function QD.ItemID(name)
  name = Str(name)
  if not name then
    return nil
  end
  Index()
  return itemByName[string.lower(name)]
end

-- "38%", "4.5%", "<0.1%".
function QD.Pct(p)
  p = tonumber(p)
  if not p then
    return nil
  end
  if p < 0.1 then
    return "<0.1%"
  end
  if p >= 10 then
    return string.format("%d%%", math.floor(p + 0.5))
  end
  local s = string.format("%.1f", p):gsub("%.0$", "")
  return s .. "%"
end

-- Sources of one item: { {npc, pct|nil}, ... }, best chance first.
function QD.Sources(itemID)
  local d = Data()
  local row = d and d.items[itemID]
  if not row then
    return {}
  end
  local out = {}
  for i = 2, #row, 2 do
    out[#out + 1] = { npc = row[i], pct = row[i + 1] or nil }
  end
  return out
end

function QD.NpcName(id)
  local d = Data()
  local n = d and d.npcs[id]
  return n and n[1] or nil
end

function QD.NpcMap(id)
  local d = Data()
  local n = d and d.npcs[id]
  return n and n[2] or 0
end

-- Objective text -> item name, have, need. "Tough Wolf Meat: 4/8" or "4/8 Tough Wolf Meat".
function QD.ParseObjective(text)
  text = Str(text)
  if not text then
    return nil
  end
  local name, a, b = text:match("^(.-):%s*(%d+)%s*/%s*(%d+)%s*$")
  if not name then
    a, b, name = text:match("^%s*(%d+)%s*/%s*(%d+)%s+(.+)$")
  end
  if not name then
    return nil
  end
  return name, tonumber(a), tonumber(b)
end

-- Every item objective still needed in the quest log:
-- { { item = id, name, have, need, quest = title }, ... }
function QD.ReadNeeds()
  local needs = {}
  local function add(text, finished, title, have, need)
    if finished then
      return
    end
    local name, a, b = QD.ParseObjective(text)
    a, b = have or a, need or b
    if not name or (a and b and a >= b) then
      return
    end
    local id = QD.ItemID(name)
    if id then
      needs[#needs + 1] = { item = id, name = name, have = a or 0, need = b or 1, quest = title }
    end
  end
  local QL = C_QuestLog
  if QL and QL.GetNumQuestLogEntries and QL.GetInfo and QL.GetQuestObjectives then
    local n = Core.Number(Core.Call(QL.GetNumQuestLogEntries)) or 0
    for i = 1, n do
      local info = Core.Call(QL.GetInfo, i)
      if type(info) == "table" and not Core.Flag(info.isHeader) then
        local qid = Core.Number(info.questID)
        local list = qid and Core.Call(QL.GetQuestObjectives, qid)
        if type(list) == "table" then
          for _, o in ipairs(list) do
            if type(o) == "table" and (o.type == nil or o.type == "item") then
              add(o.text, Core.Flag(o.finished) == true, Str(info.title),
                Core.Number(o.numFulfilled), Core.Number(o.numRequired))
            end
          end
        end
      end
    end
  elseif GetNumQuestLogEntries and GetQuestLogLeaderBoard then
    local n = Core.Number(Core.Call(GetNumQuestLogEntries)) or 0
    for i = 1, n do
      local title, _, _, isHeader = Core.Call(GetQuestLogTitle, i)
      if not isHeader then
        local m = Core.Number(Core.Call(GetNumQuestLeaderBoards, i)) or 0
        for j = 1, m do
          local text, kind, done = Core.Call(GetQuestLogLeaderBoard, j, i)
          if kind == "item" then
            add(text, done and true or false, Str(title))
          end
        end
      end
    end
  end
  return needs
end

-- Cached needs, refreshed after quest log events.
function QD.Needs()
  if QD.dirty or not QD.cache then
    QD.cache = QD.ReadNeeds()
    QD.dirty = false
  end
  return QD.cache
end

function QD.CurrentMap()
  if C_Map and C_Map.GetBestMapForUnit then
    return Core.Number(Core.Call(C_Map.GetBestMapForUnit, "player"))
  end
  return nil
end

-- One line for the Dashboard, or nil. Prefers mobs in your zone.
-- { text = "...", pct = best or nil }
function QD.Summary(itemID, mapID)
  local src = QD.Sources(itemID)
  if #src == 0 then
    return nil
  end
  local pool = src
  if mapID then
    local here = {}
    for _, s in ipairs(src) do
      if QD.NpcMap(s.npc) == mapID then
        here[#here + 1] = s
      end
    end
    if #here > 0 then
      pool = here
    end
  end
  local best, lo, hi, nPct = pool[1], nil, nil, 0
  for _, s in ipairs(pool) do
    if s.pct then
      nPct = nPct + 1
      lo = (lo == nil or s.pct < lo) and s.pct or lo
      hi = (hi == nil or s.pct > hi) and s.pct or hi
    end
  end
  local name = QD.NpcName(best.npc) or "?"
  local more = #pool - 1
  local text
  if not best.pct then
    text = "Drops from " .. name .. (more > 0 and string.format(" (+%d more)", more) or "")
  elseif more == 0 then
    text = name .. "  " .. QD.Pct(best.pct)
  elseif lo == hi and nPct == #pool then
    text = string.format("%s +%d more  %s", name, more, QD.Pct(hi))
  else
    text = string.format("%s %s  ·  %d mobs %s-%s", name, QD.Pct(best.pct), #pool, QD.Pct(lo), QD.Pct(hi))
  end
  return { text = text, pct = best.pct }
end

-- NPC id from a Creature / Vehicle GUID, or nil.
function QD.NpcFromGUID(guid)
  guid = Str(guid)
  if not guid then
    return nil
  end
  local kind, _, _, _, _, id = strsplit and strsplit("-", guid)
  if not kind then
    kind, id = guid:match("^(%a+)%-%d+%-%d+%-%d+%-%d+%-(%d+)%-")
  end
  if kind == "Creature" or kind == "Vehicle" then
    return tonumber(id)
  end
  return nil
end

-- Tooltip lines for one mob: { "Quest: Tough Wolf Meat 4/8 - drop 80%", ... }
function QD.LinesForNpc(npcIDs)
  local lines = {}
  if type(npcIDs) ~= "table" or #npcIDs == 0 then
    return lines
  end
  local want = {}
  for _, id in ipairs(npcIDs) do
    want[id] = true
  end
  for _, need in ipairs(QD.Needs()) do
    for _, s in ipairs(QD.Sources(need.item)) do
      if want[s.npc] then
        local base = string.format("Quest: %s %d/%d", need.name, need.have, need.need)
        lines[#lines + 1] = { base = base, pct = s.pct,
          text = base .. (s.pct and (" \226\128\148 drop " .. QD.Pct(s.pct)) or " \226\128\148 drops") }
        break
      end
    end
  end
  return lines
end

-- Which NPC ids a unit is: the GUID when readable, else its name (same zone first).
function QD.UnitNpcs(unit)
  if not unit then
    return {}
  end
  local id = UnitGUID and QD.NpcFromGUID(Core.Call(UnitGUID, unit))
  if id then
    return { id }
  end
  local name = Str(UnitName and Core.Call(UnitName, unit))
  if not name then
    return {}
  end
  Index()
  local ids = npcByName[string.lower(name)] or {}
  local map = QD.CurrentMap()
  if map and #ids > 1 then
    local here = {}
    for _, i in ipairs(ids) do
      if QD.NpcMap(i) == map then
        here[#here + 1] = i
      end
    end
    if #here > 0 then
      return here
    end
  end
  return ids
end

function QD.AddToTooltip(tt, unit)
  if not QD.Enabled() or not tt or not tt.AddLine then
    return
  end
  if UnitIsPlayer and Core.UnitFlag(UnitIsPlayer, unit) == true then
    return
  end
  local lines = QD.LinesForNpc(QD.UnitNpcs(unit))
  if #lines == 0 then
    return
  end
  for _, l in ipairs(lines) do
    if l.pct then
      tt:AddDoubleLine(l.base, "drop " .. QD.Pct(l.pct), 1, 0.82, 0, 0.40, 0.92, 0.62)
    else
      tt:AddDoubleLine(l.base, "drops", 1, 0.82, 0, 0.70, 0.76, 0.72)
    end
  end
  tt:AddLine(QD.NOTE, 0.5, 0.5, 0.5)
  if tt.Show then
    tt:Show()
  end
end

local function UnitOf(tt)
  if tt and tt.GetUnit then
    local ok, _, unit = pcall(tt.GetUnit, tt)
    if ok and unit and not Core.IsSecret(unit) then
      return unit
    end
  end
  if UnitExists and Core.UnitFlag(UnitExists, "mouseover") then
    return "mouseover"
  end
  return nil
end

function QD.Hook()
  if QD.hooked or not GameTooltip then
    return
  end
  QD.hooked = true
  local function post(tt)
    if tt ~= GameTooltip then
      return
    end
    if IsInInstance and Core.Flag(Core.Call(IsInInstance)) == true then
      return -- unit data is restricted in Forever instances
    end
    local unit = UnitOf(tt)
    if unit then
      pcall(QD.AddToTooltip, tt, unit)
    end
  end
  if TooltipDataProcessor and TooltipDataProcessor.AddTooltipPostCall and Enum and Enum.TooltipDataType
    and Enum.TooltipDataType.Unit and GameTooltip.GetPrimaryTooltipData then
    TooltipDataProcessor.AddTooltipPostCall(Enum.TooltipDataType.Unit, post)
  elseif GameTooltip.HasScript and GameTooltip:HasScript("OnTooltipSetUnit") then
    GameTooltip:HookScript("OnTooltipSetUnit", post)
  end
end

