#!/usr/bin/env python3
"""Nock 3.7.1: rare tameable beast spawn data (facts only, no invented numbers).

Sources
  * QuestieDB Forever (data/Forever/foreverNpcDB.lua): NPC rank, spawn points
    and patrol waypoints per zone, from the Forever client data. Zone area IDs
    are mapped to uiMapIDs with support/Forever/Zones/areaIdToUiMapId.lua.
  * CMaNGOS classic-db (Full_DB z2815 + Updates, Nov 2026), exported to
    cmangos_rares.json by the query in this folder's README notes:
      - creature.spawntimesecsmin / spawntimesecsmax  -> respawn range
      - pool_creature_template + pool_template (max_limit 1, chance 0) or
        spawn_group (MaxCount 1) -> "one alive, spawn point picked at random
        from N equal spots". Only then is a per-spot share (1 / N) shown, and
        only when QuestieDB Forever lists the same N spots.
  CMaNGOS has no placeholder data for these rares, so no source gives the
  chance that a rare is up right now: the addon says "unknown" and shows the
  respawn range instead.

Run: python3 tools/tame/gen_tame370.py  (needs /tmp/QuestieDB checkout)
Writes Nock/Data_TameSpawns.lua.
"""
import json, re, math
from pathlib import Path
from lupa.lua51 import LuaRuntime

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
Q = Path('/tmp/QuestieDB')
lua = LuaRuntime(unpack_returned_tuples=True)

def load(path, var):
    s = open(path, encoding='utf-8').read()
    i = s.index(var + ' = [[') + len(var + ' = [[')
    j = s.index(']]', i)
    while True:
        try:
            return lua.execute(s[i:j])
        except Exception:
            j = s.index(']]', j + 2)

npcs = load(Q / 'data/Forever/foreverNpcDB.lua', 'QuestieDB.npcData')
a2u = {}
for m in re.finditer(r'\[(\d+)\]\s*=\s*(\d+),', (Q / 'support/Forever/Zones/areaIdToUiMapId.lua').read_text()):
    a2u.setdefault(int(m.group(1)), int(m.group(2)))
cm = json.load(open(HERE / 'cmangos_rares.json'))
names = re.findall(r'^  \{ "([^"]+)", "', (ROOT / 'Nock/Data_Pets.lua').read_text(), re.M)

def L(t):
    return [t[k] for k in sorted(t.keys())] if t else []

def r1(v):
    return round(float(v), 1)

def thin(path, maxn=40):
    if len(path) <= maxn:
        return path
    step = (len(path) - 1) / (maxn - 1)
    return [path[round(i * step)] for i in range(maxn)]

out = []
stats = dict(rares=0, pct=0, paths=0, spawns=0)
for nm in names:
    c = cm[nm]
    nid = c['id']
    n = npcs[nid]
    rank = n[6] or 0
    maps = {}
    nspawn = 0
    for z in (n[7].keys() if n[7] else []):
        ui = a2u.get(int(z))
        if not ui:
            continue
        pts = [(r1(p[1]), r1(p[2])) for p in L(n[7][z]) if p[1] and p[1] > 0]
        if pts:
            maps.setdefault(ui, {'pts': [], 'paths': []})['pts'] += pts
            nspawn += len(pts)
    for z in (n[8].keys() if n[8] else []):
        ui = a2u.get(int(z))
        if not ui:
            continue
        for path in L(n[8][z]):
            pts = [(r1(p[1]), r1(p[2])) for p in L(path) if p[1] and p[1] > 0]
            if len(pts) >= 2:
                maps.setdefault(ui, {'pts': [], 'paths': []})['paths'].append(thin(pts))
                stats['paths'] += 1
    resp = c['resp'][0] if len(c['resp']) == 1 else None
    single = c['single'] or any(g[1] == '1' for g in c['groups'])
    pct = None
    if single and c['n'] > 1 and c['n'] == nspawn:
        pct = round(100 / c['n'])
    stats['rares'] += rank in (2, 4)
    stats['pct'] += pct is not None
    stats['spawns'] += nspawn
    out.append((nm, nid, rank, resp, c['n'], single, pct, maps))

def lua_pts(pts):
    return ', '.join(f'{x}, {y}' for x, y in pts)

lines = ['--[[',
 '  Nock 3.7.1: where each rare tameable beast spawns, and how it spawns.',
 '  Generated by tools/tame/gen_tame370.py; do not hand-edit numbers.',
 '',
 '  rank   QuestieDB Forever NPC rank (CMaNGOS enum): 4 rare, 2 rare elite, 0 normal.',
 '  resp   { min, max } respawn seconds, CMaNGOS classic-db creature.spawntimesecs.',
 '  spots  CMaNGOS spawn points; one = true when only one can be up and the spot',
 '         is picked at random with equal weight (pool max_limit 1, chance 0, or',
 '         spawn_group MaxCount 1).',
 '  pct    share per spot (100 / spots), only when one = true and QuestieDB',
 '         Forever lists the same number of spots. Not the chance it is up:',
 '         no source has placeholder data for these rares, so that is unknown.',
 '  maps   [uiMapID] = { pts = { x, y, ... }, paths = { { x, y, ... }, ... } }',
 '         spawn points and patrol paths (0-100) from QuestieDB Forever.',
 '  Classic data; Forever may differ.',
 ']]', '',
 'local Nock = _G.Nock', 'if not Nock then', '  return', 'end', '',
 'Nock.Data = Nock.Data or {}', '', 'Nock.Data.TameSpawns = {']
for nm, nid, rank, resp, nspots, single, pct, maps in out:
    parts = [f'npc = {nid}', f'rank = {rank}']
    if resp:
        parts.append(f'resp = {{ {resp[0]}, {resp[1]} }}')
    parts.append(f'spots = {nspots}')
    if single:
        parts.append('one = true')
    if pct is not None:
        parts.append(f'pct = {pct}')
    mp = []
    for ui in sorted(maps):
        m = maps[ui]
        paths = ', '.join('{ ' + lua_pts(p) + ' }' for p in m['paths'])
        mp.append(f'[{ui}] = {{ pts = {{ {lua_pts(m["pts"])} }}, paths = {{ {paths} }} }}')
    parts.append('maps = { ' + ', '.join(mp) + ' }')
    lines.append(f'  ["{nm}"] = {{ ' + ', '.join(parts) + ' },')
lines.append('}')
(ROOT / 'Nock/Data_TameSpawns.lua').write_text('\n'.join(lines) + '\n')
print(stats)
for nm, nid, rank, resp, nspots, single, pct, maps in out:
    print(f'{nm:24} rank={rank} resp={resp} spots={nspots} one={single} pct={pct} maps={ {k: (len(v["pts"]), len(v["paths"])) for k, v in maps.items()} }')
