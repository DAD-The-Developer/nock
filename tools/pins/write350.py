import json, collections
rows=json.load(open('/tmp/pins350.json')); ITEM={int(k):v for k,v in json.load(open('/tmp/items350.json')).items()}
def q(s): return '"'+s.replace('\\','\\\\').replace('"','\\"')+'"'
stocks={}; quests={}; used_items=set()
out=[]; zones={}
import re
zs=open('/tmp/QuestieDB/support/Forever/Zones/areaIdToUiMapId.lua').read()
zname={}
for m in re.finditer(r'\[(\d+)\]\s*=\s*(\d+),\s*--\s*(.*)', zs):
    zname.setdefault(int(m.group(2)), m.group(3).strip())
for r in sorted(rows,key=lambda r:(r['map'],r['kind'],r['name'],r['x'],r['y'])):
    si=0
    if r['items']:
        k=tuple(r['items'])
        if k not in stocks: stocks[k]=len(stocks)+1
        si=stocks[k]; used_items.update(k)
    qi=0
    if r['quests']:
        k=tuple(tuple(x) for x in r['quests'])
        if k not in quests: quests[k]=len(quests)+1
        qi=quests[k]
    zones[r['map']]=zname.get(r['map'],'?')
    out.append('  {%d,"%s",%d,%.1f,%.1f,%s,%s,"%s",%d,%d},'%(r['kind'],r['fac'],r['map'],r['x'],r['y'],q(r['name']),q(r['sub']),r['goods'],si,qi))
L=['--[[',
'  Nock 3.5.0: hunter NPC locations for the map pins (generated by',
'  tools/pins/gen350.py + write350.py from QuestieDB Forever; do not hand-edit).','',
'  PinData row: { kind, faction, uiMapID, x, y, name, title, goods, stock, quests }',
'    kind     main pin: 1 hunter trainer / weapon master, 2 pet trainer,',
'             3 stable master, 4 ammo, 5 bows & guns, 6 quivers & pouches,',
'             7 pet food, 8 hunter quests, 9 flight master',
'    faction  A, H, or AH (friendly to both)',
'    x, y     percent of the zone map (0-100)',
'    goods    what the vendor sells: a arrows, b bullets, q quivers, p ammo pouches,',
'             w bows, g guns, c crossbows, t thrown, M meat, F fish, B bread,',
'             C cheese, R fruit, U fungus, d drinks',
'    stock    index into PinStock (item IDs), 0 = none',
'    quests   index into PinQuests ({ name, level } hunter-only quests), 0 = none',
'  PinItems: [itemID] = { goods code, required level, name }',
'','  NPC facts and Classic-era coordinates from the community QuestieDB Forever data.',']]','',
'local Nock = _G.Nock','if not Nock then','  return','end','','Nock.PinData = {']
L+=out+['}','','Nock.PinStock = {']
for k,i in sorted(stocks.items(), key=lambda x:x[1]): L.append('  {'+','.join(str(x) for x in k)+'},')
L+=['}','','Nock.PinItems = {']
for iid in sorted(used_items):
    c,lv,nm=ITEM[iid]; L.append('  [%d] = {"%s",%d,%s},'%(iid,c,lv,q(nm)))
L+=['}','','Nock.PinQuests = {']
for k,i in sorted(quests.items(), key=lambda x:x[1]): L.append('  {'+','.join('{%s,%d}'%(q(n),lv) for n,lv in k)+'},')
L+=['}','','Nock.PinZones = {']
for m in sorted(zones): L.append('  [%d] = %s,'%(m,q(zones[m])))
L+=['}','']
open('/workspace/nock/Nock/PinsData.lua','w').write('\n'.join(L))
print(len(out),'rows',len(stocks),'stocks',len(used_items),'items',len(quests),'quest lists')
